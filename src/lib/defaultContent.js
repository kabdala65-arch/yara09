// دمج المحتوى الجاي من قاعدة البيانات فوق الافتراضي (merge عميق مستوى واحد كفاية هنا)
export function mergeContent(remote) {
  if (!remote || typeof remote !== 'object') return DEFAULT_CONTENT
  const merged = {}
  for (const key of Object.keys(DEFAULT_CONTENT)) {
    const base = DEFAULT_CONTENT[key]
    const over = remote[key]
    if (over && typeof over === 'object' && !Array.isArray(over)) {
      merged[key] = { ...base, ...over }
    } else if (over !== undefined) {
      merged[key] = over
    } else {
      merged[key] = base
    }
  }
  return merged
}
